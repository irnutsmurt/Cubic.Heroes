#!/usr/bin/env python3
"""Writes tests/scripts/soak_play.drive: a long in-play session from a save at
the castle (SAVES=), each cycle the river fight's route east into the river's
area (a transition, confirmed), eight rounds of sword swings with normal
damage, then the system menu's TITLE ("Exit game? Unsaved data will be lost."
YES) back to the title and CONTINUE: the save loaded again, at the castle.
Each cycle checks it is in play at the castle and then in the river's area;
a check that fails ends the drive (the game keeps running). Needs
DOTHEROES_DEV_KEYS=1 (marks) and DOTHEROES_DEV_STATE=1. Leaving by GAME OVER
instead (life.trigger) depended on an enemy landing a hit, which a hero
standing still often waited 90 s for in vain.

  tests/scripts/make_soak_play.py [cycles]      (default 12, ~2 min each)
"""
import os
import sys

cycles = int(sys.argv[1]) if len(sys.argv) > 1 else 12
out = [
    "# Generated by tests/scripts/make_soak_play.py: see there.",
    "log TitleMovie 120", "sleep 5", "press START", "sleep 3", "press START", "sleep 5",
    "press CROSS                 # \"Change characters?\" NO",
]
route = ["hold RIGHT 4", "hold DOWN 1.5", "hold RIGHT 3", "hold RIGHT 4", "hold RIGHT 4",
         "hold RIGHT 2.5", "hold UP 1.5", "hold RIGHT 2"]
for c in range(cycles):
    out += [f"# cycle {c + 1}", "state life>0,area==17 90", "sleep 3", *route,
            "state area==18,life>0 30", "touch mark.trigger"]
    for d in ("RIGHT", "DOWN", "LEFT", "UP") * 2:
        out += [f"hold {d} 0.15", "repeat 2 CROSS 0.35", "sleep 1"]
    out += ["touch mark.trigger",
            "press START                 # system menu, RESUME", "sleep 2",
            "press UP                    # TITLE (the list wraps)", "sleep 1",
            "press CROSS                 # \"Exit game? Unsaved data will be lost.\", on NO", "sleep 2",
            "press UP", "sleep 1", "press CROSS                 # YES: the title",
            "sleep 8", "press START                 # \"PRESS START BUTTON\"", "sleep 3",
            "press START                 # CONTINUE", "sleep 5",
            "press CROSS                 # \"Change characters?\" NO"]
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "soak_play.drive")
with open(path, "w", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print(f"{path}: {cycles} cycles")
