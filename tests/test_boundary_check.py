class Bundles(unittest.TestCase):
    def make(self, d, with_licences):
        os.makedirs(os.path.join(d, "lib"))
        open(os.path.join(d, "lib", "OpenAL32.dll"), "wb").write(b"MZ" + bytes(100))
        open(os.path.join(d, "LICENSE.txt"), "w").write("GPL-3.0")
        if with_licences:
            lic = os.path.join(d, "licenses")
            os.makedirs(os.path.join(lic, "source"))
            for _, name in build_deps.OPENAL_LICENCES + [(None, build_deps.OPENAL_NOTICE)]:
                open(os.path.join(lic, name), "w").write("x")
            buf = io.BytesIO()
            with tarfile.open(fileobj=buf, mode="w:xz") as t:
                info = tarfile.TarInfo("openal-soft-1.25.2/COPYING")
                info.size = 1
                t.addfile(info, io.BytesIO(b"x"))
            open(os.path.join(lic, "source", build_deps.openal_archive_name()), "wb").write(buf.getvalue())

    def test_licences_required(self):
        with tempfile.TemporaryDirectory() as d:
            self.make(d, with_licences=False)
            f = []
            bc.check_artifact(d, bundle=True, findings=f)
            self.assertTrue(any(c == "LICENCE" for c, _, _ in f))
        with tempfile.TemporaryDirectory() as d:
            self.make(d, with_licences=True)
            f = []
            bc.check_artifact(d, bundle=True, findings=f)
            self.assertEqual([], f)

    def test_ffmpeg_licences_required(self):
        """FFmpeg's libraries in a bundle need its licence, notice, source archive, build driver and configuration."""
        import build_ffmpeg
        needed = [build_ffmpeg.LICENCE[1], build_ffmpeg.NOTICE, "source/" + build_ffmpeg.SOURCE_ARCHIVE,
                  "source/%s/build_ffmpeg.py" % build_ffmpeg.BUILD_DIR, "source/%s/config.h" % build_ffmpeg.BUILD_DIR]
        for platform, (_, libs) in build_ffmpeg.LIB_FILES.items():
            for missing in [None] + needed:
                with tempfile.TemporaryDirectory() as d:
                    self.make(d, with_licences=True)
                    open(os.path.join(d, "lib", libs[1]), "wb").write(b"MZ" + bytes(100))
                    for rel in needed:
                        if rel != missing:
                            p = os.path.join(d, "licenses", *rel.split("/"))
                            os.makedirs(os.path.dirname(p), exist_ok=True)
                            open(p, "w").write("x")
                    f = []
                    bc.check_artifact(d, bundle=True, findings=f)
                    if missing is None:
                        self.assertEqual([], f, platform)
                    else:
                        self.assertEqual(["LICENCE"], [c for c, _, _ in f], (platform, missing))
                        self.assertIn(missing, f[0][2])

    def test_inside_archives(self):
        with tempfile.TemporaryDirectory() as d:
            self.make(d, with_licences=True)
            arc = os.path.join(d, "b.zip")
            with zipfile.ZipFile(arc, "w") as z:
                z.writestr("B/data/BGM_TITLE.WAV", b"RIFF\x24\0\0\0WAVE" + bytes(20))
            f = []
            bc.check_artifact(arc, findings=f)
            self.assertEqual(["GAME-DATA"], sorted({c for c, _, _ in f}))

    def test_source_archive_has_no_data_set(self):
        out = os.path.join(build_deps.DEPS, "src", os.path.basename(build_deps.SOURCES["OpenAL-Soft"][0]))
        if not os.path.exists(out):
            self.skipTest("OpenAL Soft's archive not fetched (tools/build_deps.py)")
        with tempfile.TemporaryDirectory() as d:
            arc, _ = build_deps.openal_source_archive(d)
            f = []
            bc.check_artifact(arc, findings=f)
            self.assertEqual([], f)
            with tarfile.open(arc) as t:
                self.assertFalse(any(n.endswith(".mhr") for n in t.getnames()))


class Hook(unittest.TestCase):
    def test_pre_push_runs_the_check(self):
        text = open(os.path.join(ROOT, "tools", "githooks", "pre-push"), encoding="utf-8").read()
        self.assertIn("boundary_check.py", text)
        head = subprocess.run(["git", "-C", ROOT, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
        r = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "boundary_check.py"), "pre-push"],
                           input=f"refs/heads/main {head} refs/heads/main {'0' * 40}\n", capture_output=True, text=True)
        self.assertEqual(0, r.returncode, r.stdout)


