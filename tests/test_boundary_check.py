def classes(path, data):
    f = []
    bc.check_bytes(path, data, f)
    return sorted({c for c, _, _ in f})


def elf_header(machine, big_endian=True, cls=2):
    h = bytearray(64)
    h[:4] = b"\x7fELF"
    h[4], h[5], h[6] = cls, 2 if big_endian else 1, 1
    h[18:20] = machine.to_bytes(2, "big" if big_endian else "little")
    return bytes(h)


def coff_object(defined, undefined=()):
    """A minimal x86-64 COFF object: one .text section, the symbols named (long names in the string table)."""
    syms, strtab = [], bytearray(4)
    for name, section in [(n, 1) for n in defined] + [(n, 0) for n in undefined]:
        raw = name.encode()
        if len(raw) <= 8:
            field = raw.ljust(8, b"\0")
        else:
            field = b"\0\0\0\0" + struct.pack("<I", len(strtab))
            strtab += raw + b"\0"
        syms.append(field + struct.pack("<IhHBB", 0, section, 0x20, 2, 0))
    strtab[:4] = struct.pack("<I", len(strtab))
    header_size, section_size = 20, 40
    symptr = header_size + section_size
    head = struct.pack("<HHIIIHH", 0x8664, 1, 0, symptr, len(syms), 0, 0)
    section = b".text\0\0\0" + bytes(32)
    return head + section + b"".join(syms) + bytes(strtab)


def ar_archive(members):
    out = bytearray(binsyms.AR_MAGIC)
    for name, data in members:
        hdr = ((name + "/").ljust(16) + "0".ljust(12) + "0".ljust(6) * 2 + "644".ljust(8)
               + str(len(data)).ljust(10)).encode() + b"`\n"
        out += hdr + data + (b"\n" if len(data) & 1 else b"")
    return bytes(out)


LIFTED_PPU = b"".join(b"void func_%08X(ppu_context* ctx) {\n    ctx->gpr[3] = 0;\n}\n" % (0x10000 + 4 * i)
                      for i in range(20))
PATCH = b"""// a native patch: replaces one game routine, calls two others
#include "ppu_recomp.h"
extern void func_0046E0EC(ppu_context* ctx);
extern void func_0046F4BC(ppu_context* ctx);
void my_patch(ppu_context* ctx) { func_0046E0EC(ctx); func_0046F4BC(ctx); }
"""


class Refused(unittest.TestCase):
    def test_game_files_by_name(self):
        for n in ("data/x.tpk", "a/b.dsb", "BGM.WAV", "intro.bik", "SAVE/DATA.EDT", "PARAM.SFO", "c.spv"):
            self.assertIn("GAME-DATA", classes(n, b"\0" * 32), n)

    def test_game_files_by_content(self):
        self.assertIn("GAME-DATA", classes("x.bin", b"RIFF\x24\0\0\0WAVEfmt " + bytes(20)))
        self.assertIn("GAME-DATA", classes("x.bin", b"BIKi" + bytes(20)))
        self.assertIn("GAME-DATA", classes("x.bin", b"DDS " + bytes(20)))
        self.assertIn("GAME-DATA", classes("x.bin", b"\0PSF" + bytes(20)))

    def test_ps3_binaries(self):
        self.assertEqual(["PS3-BINARY"], classes("x.bin", elf_header(21)))          # PPU
        self.assertEqual(["PS3-BINARY"], classes("x.bin", elf_header(23, cls=1)))   # SPU
        for magic in (b"SCE\0", b"\x7fPKG", b"SCEUF", b"NPD\0"):
            self.assertIn("PS3-BINARY", classes("x.bin", magic + bytes(28)), magic)

    def test_lifted_source(self):
        self.assertEqual(["LIFTED-CODE"], classes("x.cpp", b"/* Auto-generated by ppu_lifter.py -- do not edit */\n"))
        self.assertEqual(["LIFTED-CODE"], classes("x.c", b"/* Auto-generated by spu_lifter.py */\n"))
        self.assertEqual(["LIFTED-CODE"], classes("renamed.cpp", LIFTED_PPU))

    def test_generated_source(self):
        text = b"// The water -- native code GENERATED on this machine by tools/gen_spu_native.py from the lift\n"
        self.assertEqual(["GENERATED"], classes("w.cpp", text))

    def test_compiled_lifted_and_generated(self):
        lifted = coff_object(["func_%08X" % (0x10000 + 4 * i) for i in range(10)])
        self.assertEqual(["LIFTED-CODE"], classes("x.o", lifted))
        self.assertEqual(["LIFTED-CODE"], classes("lib.a", ar_archive([("x.o", lifted)])))
        gen = coff_object(["_ZN9water_gen4callEPh", "_ZN9water_gen12_GLOBAL__N_17f_03050ERNS0_3RunE"])
        self.assertEqual(["GENERATED"], classes("g.o", gen))
        self.assertEqual(["LIFTED-CODE"], classes("dotheroes.exe", b"MZ" + bytes(62)))
        self.assertEqual(["LIFTED-CODE"], classes("install/dotheroes", elf_header(62, big_endian=False)))

    def test_keys(self):
        line = b"APP 1C " + b"0123456789abcdef" * 4 + b" " + b"fedcba9876543210" * 2 + b"\n"
        self.assertEqual(["KEYS"], classes("k.txt", line))
        self.assertEqual(["KEYS"], classes("k.cfg", b"klic = " + b"00112233445566778899aabbccddeeff" + b"\n"))

    def test_save_data(self):
        png = b"\x89PNG\r\n\x1a\n" + bytes(24)
        # a save copied beside the checkout: its icon is an ordinary PNG, refused by where it sits and its name
        for n in ("gamespy_3ddot_link/PS3/SAVEDATA/BLJM60180T0019C558F0/ICON0.PNG",
                  "x/dev_hdd0/home/00000001/savedata/BLUS30490SYSTEM/ICON0.PNG", "copy/PIC1.PNG"):
            self.assertIn("SAVE-DATA", classes(n, png), n)
        # a save's data file without a known extension, by its folders alone
        self.assertIn("SAVE-DATA", classes("backup/BLUS30490GAME-DATA66BE2553/SYS-DATA", bytes(32)))
        self.assertIn("SAVE-DATA", classes("a/SaveData/slot/x.bin", bytes(32)))
        self.assertIn("SAVE-DATA", classes("bundle.zip!/BLES00000/USRDIR/x.bin", bytes(32)))
        self.assertIn("GAME-DATA", classes("gamedata/dev_hdd0/game/x/y.bin", bytes(32)))
        self.assertIn("GAME-DATA", classes("disc/PS3_GAME/USRDIR/data/x.bin", bytes(32)))
        self.assertIn("PS3-BINARY", classes("fw/dev_flash/sys/x.bin", bytes(32)))

    def test_save_folders_ignored(self):
        for p in ("gamespy_3ddot_link/PS3/SAVEDATA/BLJM60180T0019/ICON0.PNG",
                  "gamedata/dev_hdd0/home/00000001/savedata/BLUS30490SYSTEM/PARAM.SFO",
                  "anywhere/PS3/SAVEDATA/BLUS30490X/DATA.EDT", "anywhere/dev_flash/x.bin"):
            r = subprocess.run(["git", "-C", ROOT, "check-ignore", "-q", "--no-index", p])
            self.assertEqual(0, r.returncode, p)

    def test_middleware_and_data_set(self):
        self.assertIn("MIDDLEWARE", classes("port/native/fmod_mixer.cpp", b"// x\n"))
        self.assertIn("DATA-SET", classes("hrtf/Default HRTF.mhr", b"MinPHR03" + bytes(20)))


