def tree(findings=None):
    findings = [] if findings is None else findings
    for p in GENERATED_PATHS:
        if subprocess.run(["git", "-C", ROOT, "check-ignore", "-q", "--no-index", p]).returncode != 0:
            findings.append(("NOT-IGNORED", p, "a generated-output path git would add"))
    files = [f for f in git("ls-files", "-z", "--others", "--exclude-standard").decode("utf-8", "replace").split("\0") if f]
    for f in files:
        try:
            with open(os.path.join(ROOT, f), "rb") as h:
                data = h.read(64 << 20)
        except OSError:
            continue
        check_bytes(f, data, findings)
    return findings, len(files)


# Pinned exceptions (the owner's decision of 2026-11-13, docs/FFMPEG_MIGRATION_PLAN.md section 6.1): files inside one
# exact third-party archive that a rule refuses by their name alone, though they are not what the rule is for. Each
# is excused only when the archive's own SHA-256, the member's path inside it and the member's own SHA-256 all match;
# anything else -- another archive, another path, a byte changed -- is checked as before. Not an exception for a
# file type or for the archive: every other member of it is checked in full.
PINNED = [
    # FFmpeg 9.0.2's release archive (config/deps.sha256), shipped as the libraries' corresponding source: two of
    # FFmpeg's FATE test references, three lines of text each (an md5, a size, a CRC), named for the test that
    # writes peak.wav -- no sound in them
    {"archive": "6e374ed621e48faa40639307dff48ba6fe574a509977956d2cce9669b7cc27e9",
     "member": "FFmpeg-n9.0.2/tests/ref/lavf/peak.wav",
     "sha256": "f609e9a152cbdcd35e6969a57df5792c8f74cfc4787718af2da806e809c5f7b3",
     "why": "FFmpeg's FATE test reference (text), not a sound"},
    {"archive": "6e374ed621e48faa40639307dff48ba6fe574a509977956d2cce9669b7cc27e9",
     "member": "FFmpeg-n9.0.2/tests/ref/lavf/peak_only.wav",
     "sha256": "97d101ddb1f01fad7929008b40214fc4c72f91b01940e20f38b99507972c1ded",
     "why": "FFmpeg's FATE test reference (text), not a sound"},
]
_archive_sha = {}   # an archive's name in a walk -> its SHA-256 (nested() records it as it opens one)


def pinned(name, data):
    """The pinned exception covering this file of a walk (its archive, its path in it and its bytes all as pinned),
    else None."""
    if "!/" not in name:
        return None
    archive, member = name.rsplit("!/", 1)
    sha = _archive_sha.get(archive)
    for p in PINNED:
        if p["archive"] == sha and p["member"] == member and p["sha256"] == hashlib.sha256(data).hexdigest():
            return p
    return None


def walk_artifact(path):
    """(name, bytes) of every file in a folder, a .zip or a .tar(.xz/.gz/.bz2), archives inside included."""
    if os.path.isdir(path):
        for d, _, fs in os.walk(path):
            for f in fs:
                p = os.path.join(d, f)
                rel = os.path.relpath(p, path).replace(os.sep, "/")
                with open(p, "rb") as h:
                    data = h.read()
                yield rel, data
                yield from nested(rel, data)
        return
    with open(path, "rb") as h:
        data = h.read()
    yield os.path.basename(path), data
    yield from nested(os.path.basename(path), data)


def nested(name, data):
    low = name.lower()
    if (low.endswith(".zip") and data[:2] == b"PK") or low.endswith((".tar", ".tar.xz", ".txz", ".tar.gz", ".tgz",
                                                                        ".tar.bz2")):
        _archive_sha[name] = hashlib.sha256(data).hexdigest()
    if low.endswith(".zip") and data[:2] == b"PK":
        with zipfile.ZipFile(io.BytesIO(data)) as z:
            for i in z.infolist():
                if not i.is_dir():
                    d = z.read(i)
                    yield name + "!/" + i.filename, d
                    yield from nested(name + "!/" + i.filename, d)
    elif low.endswith((".tar", ".tar.xz", ".txz", ".tar.gz", ".tgz", ".tar.bz2")):
        try:
            with tarfile.open(fileobj=io.BytesIO(data)) as t:
                for m in t.getmembers():
                    if m.isfile():
                        d = t.extractfile(m).read()
                        yield name + "!/" + m.name, d
                        yield from nested(name + "!/" + m.name, d)
        except tarfile.TarError:
            pass


def bundle_licences(names, findings, where):
    """A bundle carries the licence and notice of each library it ships, and OpenAL Soft's and FFmpeg's source."""
    import build_deps
    has = lambda suffix: any(n.endswith(suffix) for n in names)  # noqa: E731
    if has("/OpenAL32.dll") or has("/libopenal.so.1") or has("OpenAL32.dll") or has("libopenal.so.1"):
        for _, lic in build_deps.OPENAL_LICENCES:
            if not has("licenses/" + lic):
                findings.append(("LICENCE", where, f"OpenAL Soft shipped without licenses/{lic}"))
        if not has("licenses/" + build_deps.OPENAL_NOTICE):
            findings.append(("LICENCE", where, "OpenAL Soft shipped without its notice"))
        if not has("licenses/source/" + build_deps.openal_archive_name()):
            findings.append(("LICENCE", where, "OpenAL Soft shipped without its source (LGPL)"))
    import build_ffmpeg
    if any(has("/" + lib) or has(lib) for _, libs in build_ffmpeg.LIB_FILES.values() for lib in libs):
        for name, what in ((build_ffmpeg.LICENCE[1], "its licence"), (build_ffmpeg.NOTICE, "its notice"),
                           ("source/" + build_ffmpeg.SOURCE_ARCHIVE, "its source (LGPL)"),
                           ("source/%s/build_ffmpeg.py" % build_ffmpeg.BUILD_DIR, "its build driver"),
                           ("source/%s/config.h" % build_ffmpeg.BUILD_DIR, "its configuration as built")):
            if not has("licenses/" + name):
                findings.append(("LICENCE", where, f"FFmpeg shipped without {what} (licenses/{name})"))
    for lib, lic in (("SDL2.dll", "SDL2.txt"), ("libSDL2-2.0.so.0", "SDL2.txt")):
        if has(lib) and not has("licenses/" + lic):
            findings.append(("LICENCE", where, f"{lib} shipped without licenses/{lic}"))
    if not has("LICENSE.txt"):
        findings.append(("LICENCE", where, "the project's own licence (LICENSE.txt) missing"))


def check_artifact(path, bundle=False, findings=None, quiet=False):
    """The findings for one artifact; printed unless quiet. Returns 1 when anything is found."""
    own = findings is None
    findings = [] if own else findings
    names = []
    excused = []
    for name, data in walk_artifact(path):
        names.append(name)
        p = pinned(name, data)
        if p:
            excused.append((name, p["why"]))
            continue
        check_bytes(name, data, findings)
    if not quiet:
        for name, why in excused:
            print(f"[boundary] pinned exception: {name} ({why}; the archive, the path and the bytes as pinned)")
    if bundle:
        bundle_licences(names, findings, os.path.basename(path))
    if own and not quiet:
        return report(findings, f"{path} ({len(names)} files)")
    return 1 if findings else 0


def report(findings, what):
    if not findings:
        print(f"[boundary] {what}: nothing outside the boundary")
        return 0
    print(f"[boundary] {what}: {len(findings)} finding(s)")
    for cls, name, why in findings:
        print(f"  {cls:12} {name}: {why}")
    return 1


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    mode, args = sys.argv[1], sys.argv[2:]
    if mode == "tracked":
        rev = args[args.index("--rev") + 1] if "--rev" in args else None
        f, n = tracked(rev)
        return report(f, f"{'commit ' + rev if rev else 'tracked files'} ({n} files)")
    if mode == "tree":
        f, n = tree()
        return report(f, f"working tree ({n} untracked files git would add, {len(GENERATED_PATHS)} output paths)")
    if mode == "artifact":
        bundle = "--bundle" in args
        rc = 0
        for p in [a for a in args if a != "--bundle"]:
            rc |= check_artifact(p, bundle=bundle)
        return rc
    if mode == "pre-push":
        zero = "0" * 40
        findings, n = [], 0
        for line in sys.stdin.read().splitlines():
            parts = line.split()
            if len(parts) == 4 and parts[1] != zero:
                f, k = tracked(parts[1])
                findings += f
                n += k
        return report(findings, f"pushed trees ({n} files)")
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
