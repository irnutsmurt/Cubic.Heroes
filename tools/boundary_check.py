#!/usr/bin/env python3
"""The player-side recompilation boundary, checked (README "What this repository is"; CLAUDE.md "Architecture
requirements"). This project distributes the tools that rebuild the game from the player's own disc, never the
game: no extracted or translated game code, no game executable or game-derived object, no game asset, sound,
music, texture or movie, no proprietary middleware implementation, no keys or firmware. Whatever is made from
the player's files (the lift, the generated native tasks, the compiled objects, the game) exists only on the
player's machine, under the install's data/gen and data/cache, or in a developer's ignored build/ folder.

  tools/boundary_check.py tracked [--rev <commit>]   the tracked files (default: the index), or a commit's tree
  tools/boundary_check.py tree                       the working tree: what `git add -A` would add (untracked and
                                                     not ignored), and that the generated-output paths are ignored
  tools/boundary_check.py artifact [--bundle] <path>...
                                                     a setup bundle (folder, .zip, .tar.xz), a prebuilt library
                                                     folder or any file; --bundle: the licences a bundle must carry
  tools/boundary_check.py pre-push                   (tools/githooks/pre-push) every pushed tip's tree, as tracked

What is refused (each file by its name and its bytes, not by where it sits):
  GAME-DATA      the game's file types (.tpk .dsb .dpk .edt .bik .sav .sfo .trp .pfd .spk .gtf .dds .at3 .vag
                 .wav .spv ...) and their contents (RIFF WAVE, Bink, DDS, PARAM.SFO); anything inside a PS3 file
                 system or disc folder (dev_hdd0, dev_bdvd, PS3_GAME, USRDIR)
  SAVE-DATA      a player's saves: anything inside a SAVEDATA folder or a folder named for a PS3 title ID
                 (BLUS30490..., BLJM60180T...), and the PS3 metadata files (ICON0.PNG, PARAM.SFO, PARAM.PFD,
                 PIC1.PNG, TROPUSR.DAT ...) wherever they are
  PS3-BINARY     PS3 executables and containers: PPU/SPU ELF (big-endian PPC64, SPU), SCE (SELF, SPRX), PKG,
                 PUP (firmware), NPD (EDAT/SDAT)
  LIFTED-CODE    the lifter's output (its header, or lifted function definitions in bulk); an object or library
                 that DEFINES lifted functions (a reference -- a native patch calling a lifted function by name --
                 is allowed); a built game executable
  GENERATED      code made by tools/gen_spu_native.py from the player's lift, source or compiled
  KEYS           decryption keys (the keys file's APP lines, erk/riv/klic values)
  MIDDLEWARE     the FMOD-derived files removed in M1 (tools/license_audit.py's FORBIDDEN)
  DATA-SET       data sets the project does not redistribute (OpenAL Soft's default HRTF, .mhr)
  LICENCE        (--bundle) a shipped library without its licence, notice or, for OpenAL Soft, its source
Exit 1 with each finding listed when anything is found.
"""
import hashlib
import io
import os
import re
import subprocess
import sys
import tarfile
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import binsyms  # noqa: E402

GAME_EXT = {".tpk", ".dsb", ".dpk", ".edt", ".bik", ".bk2", ".sav", ".sfo", ".trp", ".pfd", ".spk", ".gtf",
            ".dds", ".at3", ".at9", ".vag", ".wav", ".spv", ".self", ".sprx", ".sdat", ".edat", ".pup", ".pkg",
            ".rap", ".mhr", ".iso"}
# extensions refused only when the bytes say so too (they are common elsewhere)
MAGIC = [
    (b"SCE\0", "PS3-BINARY", "an SCE container (SELF/SPRX)"),
    (b"\x7fPKG", "PS3-BINARY", "a PS3 package"),
    (b"SCEUF", "PS3-BINARY", "a PS3 firmware update (PUP)"),
    (b"NPD\0", "PS3-BINARY", "an NPD container (EDAT/SDAT)"),
    (b"\0PSF", "GAME-DATA", "a PARAM.SFO"),
    (b"DDS ", "GAME-DATA", "a DDS texture"),
    (b"MinPHR", "DATA-SET", "an HRTF data set (.mhr)"),
]
BINK = re.compile(rb"^(?:BIK[a-z]|KB2[a-z])")
LIFTER_HEADER = re.compile(rb"Auto-generated by (?:ppu|spu)_lifter\.py")
GEN_HEADER = re.compile(rb"native code GENERATED on this machine by tools/gen_spu_native\.py")
PPU_DEF = re.compile(rb"^\s*(?:extern\s+\"C\"\s+)?(?:static\s+)?void\s+func_[0-9A-F]{8}\s*\(\s*ppu_context\s*\*", re.M)
SPU_DEF = re.compile(rb"^\s*(?:static\s+)?void\s+spu_[0-9a-f]{4}_at_[0-9A-F]{8}_spu_func_[0-9A-F]{8}\s*\(", re.M)
PPU_SYM = re.compile(r"func_[0-9A-F]{8}")
SPU_SYM = re.compile(r"spu_[0-9a-f]{4}_at_[0-9A-F]{8}_spu_func_")
KEY_LINE = re.compile(rb"^\s*APP\s+(?:0x)?[0-9A-Fa-f]+\s+[0-9A-Fa-f]{64}\s+[0-9A-Fa-f]{32}\b", re.M)
KEY_NAMED = re.compile(rb"\b(?:erk|riv|klic(?:ensee)?|idps)\b\s*[=:]\s*(?:0x)?[0-9A-Fa-f]{32}", re.I)
# A player's saves and the PS3 file system around the game: refused by where they sit as well as by name and bytes
# (a save's DATA.EDT and PARAM.SFO are caught above, but its icon is an ordinary PNG). The folders, by name:
PS3_FOLDERS = {
    "savedata": ("SAVE-DATA", "inside a PS3 save folder"),
    "dev_hdd0": ("GAME-DATA", "inside a PS3 file system (dev_hdd0: saves, installed game data)"),
    "dev_hdd1": ("GAME-DATA", "inside a PS3 file system (dev_hdd1)"),
    "dev_usb000": ("GAME-DATA", "inside a PS3 file system (dev_usb000)"),
    "dev_bdvd": ("GAME-DATA", "inside a PS3 disc (dev_bdvd)"),
    "ps3_game": ("GAME-DATA", "inside a PS3 disc's game folder (PS3_GAME)"),
    "usrdir": ("GAME-DATA", "inside a PS3 game's data folder (USRDIR)"),
    "dev_flash": ("PS3-BINARY", "inside PS3 firmware (dev_flash)"),
}
# a save, a game install or a patch folder is named for the game's title ID (BLUS30490..., BLJM60180T0019...)
TITLE_FOLDER = re.compile(r"^(?:BL|BC|NP)[A-Z]{2}\d{5}")
# the metadata files every PS3 game, save and trophy set carries
PS3_META = {"icon0.png", "icon1.pam", "pic0.png", "pic1.png", "pic2.png", "snd0.at3", "param.sfo", "param.pfd",
            "trophy.trp", "tropconf.sfm", "tropusr.dat", "tropsys.dat"}
# a definition count this high is lifted code, not a hand-written override
LIFTED_DEFS = 8
LIFTED_STRINGS = 500   # a linked binary naming this many lifted functions was built from the lift
GENERATED_NAMESPACES = None


# what port/native/spu_native_absent.cpp defines in each <task>_gen namespace when no code is generated: the
# interface alone (spu_native.h)
GENERATED_INTERFACE = {"load", "call", "has_entry", "kSource"}


def generated_namespaces():
    """The namespaces tools/gen_spu_native.py puts each task in (<task>_gen), from tools/spu_native/, as they
    appear in a mangled name: <length><task>_gen<length><next name>."""
    global GENERATED_NAMESPACES
    if GENERATED_NAMESPACES is None:
        d = os.path.join(ROOT, "tools", "spu_native")
        names = [os.path.splitext(f)[0] for f in os.listdir(d) if f.endswith(".py")] if os.path.isdir(d) else []
        GENERATED_NAMESPACES = re.compile(r"\d+(?:%s)_gen(\d+)([A-Za-z_]\w*)" % "|".join(map(re.escape, names))) \
            if names else re.compile(r"(?!)")
    return GENERATED_NAMESPACES


def generated_defs(syms):
    """The symbols that are generated code: in a <task>_gen namespace and not the interface the stub defines."""
    out = []
    for s in syms:
        m = generated_namespaces().search(s)
        if m and m.group(2)[:int(m.group(1))] not in GENERATED_INTERFACE:
            out.append(s)
    return out


def forbidden_paths():
    import license_audit
    return [p for prefixes, _ in license_audit.FORBIDDEN for p in prefixes]


def is_template(data):
    return b"@TITLE@" in data[:4096]


def check_bytes(path, data, findings, linked_ok=()):
    """Every finding for one file (its path as it would be published, its bytes)."""
    name = path.replace("\\", "/")
    base = name.rsplit("/", 1)[-1]
    ext = os.path.splitext(base)[1].lower()

    def add(cls, why):
        findings.append((cls, name, why))

    if any(name.startswith(p) or ("/" + p) in name for p in forbidden_paths()):
        add("MIDDLEWARE", "an FMOD-derived file removed in M1")
    folders = [c for c in name.replace("!/", "/").split("/")[:-1] if c]
    for c in folders:
        if c.lower() in PS3_FOLDERS:
            add(*PS3_FOLDERS[c.lower()])
            break
    if any(TITLE_FOLDER.match(c) for c in folders):
        add("SAVE-DATA", "in a folder named for a PS3 title ID (a save, a game install or a patch)")
    if base.lower() in PS3_META:
        add("SAVE-DATA", f"a PS3 game or save metadata file ({base})")
    if ext in GAME_EXT:
        add("DATA-SET" if ext == ".mhr" else "PS3-BINARY" if ext in (".self", ".sprx", ".pup", ".pkg", ".sdat", ".edat")
            else "KEYS" if ext == ".rap" else "GAME-DATA", f"a {ext} file")
    head = data[:64]
    for magic, cls, why in MAGIC:
        if head.startswith(magic):
            add(cls, why)
    if head[:4] == b"RIFF" and head[8:12] == b"WAVE":
        add("GAME-DATA", "a WAVE sound")
    if BINK.match(head):
        add("GAME-DATA", "a Bink movie")
    if head[:4] == b"\x7fELF" and head[5] == 2:   # big-endian: the PS3's
        machine = int.from_bytes(head[18:20], "big")
        if machine in (21, 23):
            add("PS3-BINARY", "a PS3 %s ELF" % ("PPU" if machine == 21 else "SPU"))
    # source code
    if LIFTER_HEADER.search(data[:512]):
        add("LIFTED-CODE", "the lifter's output")
    elif len(PPU_DEF.findall(data)) >= LIFTED_DEFS or len(SPU_DEF.findall(data)) >= LIFTED_DEFS:
        add("LIFTED-CODE", "lifted functions defined in bulk")
    if GEN_HEADER.search(data[:2048]) and not is_template(data):
        add("GENERATED", "gen_spu_native.py's output")
    if KEY_LINE.search(data) or KEY_NAMED.search(data):
        add("KEYS", "a decryption key")
    # compiled code
    syms = binsyms.defined_symbols(data) if (data.startswith(binsyms.AR_MAGIC) or ext in (".o", ".obj")) else []
    if syms:
        lifted = [s for s in syms if PPU_SYM.search(s) or SPU_SYM.search(s)]
        gen = generated_defs(syms)
        if len(lifted) >= LIFTED_DEFS:
            add("LIFTED-CODE", f"defines {len(lifted)} lifted functions (e.g. {lifted[0]})")
        if gen:
            add("GENERATED", f"defines generated code (e.g. {gen[0]})")
    elif head[:2] == b"MZ" or (head[:4] == b"\x7fELF" and head[5] == 1):
        n = len(set(re.findall(rb"func_[0-9A-F]{8}", data)))
        if n >= LIFTED_STRINGS and base not in linked_ok:
            add("LIFTED-CODE", f"a binary naming {n} lifted functions (a built game)")
        # the game's name (tools/setup_pipeline.py GAME, port/CMakeLists.txt): not the setup app, DotHeroes-Setup
        if base.lower() in ("dotheroes", "dotheroes.exe"):
            add("LIFTED-CODE", "a built game executable")


def git(*a):
    return subprocess.run(["git", "-C", ROOT] + list(a), capture_output=True).stdout


def tracked(rev=None, findings=None):
    findings = [] if findings is None else findings
    if rev:
        listing = git("ls-tree", "-r", "-z", rev).split(b"\0")
        entries = [(e.split(b"\t", 1)[1].decode("utf-8", "replace"), e.split()[2].decode()) for e in listing if b"\t" in e
                   and e.split()[1] == b"blob"]
        for path, sha in entries:
            check_bytes(path, git("cat-file", "blob", sha), findings)
        return findings, len(entries)
    files = [f for f in git("ls-files", "-z").decode("utf-8", "replace").split("\0") if f]
    for f in files:
        try:
            data = open(os.path.join(ROOT, f), "rb").read()
        except OSError:
            continue
        check_bytes(f, data, findings)
    return findings, len(files)


