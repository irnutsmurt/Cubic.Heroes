#!/usr/bin/env python3
"""Reproducible pipeline: user's disc image -> generated recompiled sources.

Every stage writes under build/ (git-ignored) and is skipped when its output
is newer than its inputs, so re-running is cheap.

  python tools/pipeline.py --iso "<your BLUS-30490 image>.iso" --keys <keys.txt>
  python tools/pipeline.py --iso ... --elf <already-decrypted EBOOT.elf>

Stages
  toolchain clone ps3recomp at the pinned revision, apply patches/ps3recomp/*.patch
  verify   image size/sha256 against config/game_version.json
  extract  Joliet tree -> build/disc
  decrypt  EBOOT.BIN -> build/EBOOT.elf (keys from the user; never shipped)
  load     ps3recomp ppu_loader.py   -> build/gen/out/EBOOT.*.json
  fixfn    tools/fix_functions.py    -> build/gen/out/EBOOT.functions.fixed.json
  lift     ps3recomp ppu_lifter.py   -> build/gen/recompiled/ (48 stable chunks)
  spu      ps3recomp SPU extract+lift -> build/gen/spu/

The HLE NID table is generated by the port build itself (port/CMakeLists.txt),
from the patched runtime's library headers.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(ROOT, "build")
GEN = os.path.join(BUILD, "gen")
VERSION = json.load(open(os.path.join(ROOT, "config", "game_version.json")))
PS3RECOMP = os.environ.get("PS3RECOMP_DIR", os.path.join(BUILD, "ref", "ps3recomp"))
TOOLS = os.path.join(PS3RECOMP, "tools")
PY = sys.executable
PS3RECOMP_URL = "https://github.com/sp00nznet/ps3recomp"
PS3RECOMP_REV = "4e8f3ca87a3e1d87bb83b8b7e9348fe2685cd514"
PATCHES = os.path.join(ROOT, "patches", "ps3recomp")
PPU_CHUNKS = "48"   # ~60k lines per TU: fits a 16 GB machine at -j4


def log(stage, msg):
    print(f"[{stage}] {msg}", flush=True)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fresh(outputs, inputs):
    """True if every output exists and is newer than every input."""
    if not all(os.path.exists(o) for o in outputs):
        return False
    oldest = min(os.path.getmtime(o) for o in outputs)
    return all(os.path.getmtime(i) <= oldest for i in inputs if os.path.exists(i))


def run(stage, args):
    log(stage, " ".join(os.path.relpath(a, ROOT) if os.path.isabs(a) else a for a in args))
    subprocess.run(args, check=True)


def git(*args, **kw):
    return subprocess.run(["git", "-C", PS3RECOMP, "-c", "user.name=dotheroes",
                           "-c", "user.email=dotheroes@localhost", *args],
                          check=True, text=True, capture_output=True, **kw).stdout


def toolchain():
    """Pinned ps3recomp + this project's patch series on branch `dotheroes`."""
    patches = sorted(os.path.join(PATCHES, f) for f in os.listdir(PATCHES) if f.endswith(".patch"))
    want = hashlib.sha256(PS3RECOMP_REV.encode() + b"".join(open(f, "rb").read() for f in patches)).hexdigest()
    stamp = os.path.join(PS3RECOMP, ".dotheroes_patchset")
    if not os.path.isdir(os.path.join(PS3RECOMP, ".git")):
        run("toolchain", ["git", "clone", "-q", PS3RECOMP_URL, PS3RECOMP])
    elif os.path.exists(stamp) and open(stamp).read().strip() == want:
        log("toolchain", f"ps3recomp {PS3RECOMP_REV[:7]} + {len(patches)} patch(es)")
        return
    if git("status", "--porcelain", "--untracked-files=no").strip():
        sys.exit(f"[toolchain] {PS3RECOMP} has uncommitted changes; commit them to patches/ first")
    git("checkout", "-q", "-B", "dotheroes", PS3RECOMP_REV)
    if patches:
        git("am", "-q", "--keep-cr", *patches)
    open(stamp, "w").write(want + "\n")
    log("toolchain", f"ps3recomp {PS3RECOMP_REV[:7]} + {len(patches)} patch(es) applied")


def spu_text_ea(eboot, image):
    """Guest EA of an extracted SPU image's executable segment inside the EBOOT:
    where its loader DMAs the code from."""
    import struct
    e, b = open(eboot, "rb").read(), open(image, "rb").read()
    at = e.find(b[:0x200])
    if at < 0 or e.find(b[:0x200], at + 1) >= 0:
        sys.exit(f"[spu] {os.path.basename(image)}: not found exactly once in the EBOOT")
    phoff, phn = struct.unpack(">I", b[0x1C:0x20])[0], struct.unpack(">H", b[0x2C:0x2E])[0]
    text = None
    for i in range(phn):
        t, off, va, pa, fsz, msz, fl, al = struct.unpack(">8I", b[phoff + i * 32:phoff + i * 32 + 32])
        if t == 1 and fl & 1:
            text = off
    eph, ephn = struct.unpack(">Q", e[0x20:0x28])[0], struct.unpack(">H", e[0x38:0x3A])[0]
    for i in range(ephn):
        t, fl, off, va, pa, fsz, msz, al = struct.unpack(">IIQQQQQQ", e[eph + i * 56:eph + i * 56 + 56])
        if t == 1 and off <= at < off + fsz:
            return va + at - off + text
    sys.exit(f"[spu] {os.path.basename(image)}: not inside a loadable EBOOT segment")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--iso", required=True)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--keys", help="keys file for SELF decryption (see docs/SETUP.md)")
    g.add_argument("--elf", help="an EBOOT.elf you already decrypted")
    ap.add_argument("--skip-verify", action="store_true")
    a = ap.parse_args()

    os.makedirs(GEN, exist_ok=True)
    toolchain()
    tools = os.path.join(ROOT, "tools")
    disc = os.path.join(BUILD, "disc")
    eboot_bin = os.path.join(disc, "PS3_GAME", "USRDIR", "EBOOT.BIN")
    elf = os.path.join(BUILD, "EBOOT.elf")

    # verify
    stamp = os.path.join(BUILD, ".iso_verified")
    if not a.skip_verify and not fresh([stamp], [a.iso]):
        want = VERSION["disc_image"]
        if os.path.getsize(a.iso) != want["size"]:
            sys.exit(f"[verify] size mismatch: this is not BLUS-30490 v01.00 (decrypted)")
        log("verify", "hashing disc image ...")
        if sha256(a.iso) != want["sha256"]:
            sys.exit("[verify] sha256 mismatch: unsupported dump (see config/game_version.json)")
        open(stamp, "w").write(want["sha256"] + "\n")
    log("verify", "ok")

    # extract
    if not fresh([eboot_bin], [a.iso]):
        run("extract", [PY, os.path.join(tools, "iso9660.py"), "extract", a.iso, disc])
    if sha256(eboot_bin) != VERSION["files"]["PS3_GAME/USRDIR/EBOOT.BIN"]:
        sys.exit("[extract] EBOOT.BIN hash mismatch")

    # decrypt
    if a.elf:
        elf = os.path.abspath(a.elf)
    elif not fresh([elf], [eboot_bin]):
        run("decrypt", [PY, os.path.join(tools, "self_decrypt.py"), "--keys", a.keys, eboot_bin, elf])
    if sha256(elf) != VERSION["decrypted_elf"]["sha256"]:
        sys.exit("[decrypt] EBOOT.elf hash mismatch")
    log("decrypt", "EBOOT.elf ok")
    # The runtime derives its /dev_bdvd root from <root>/PS3_GAME/USRDIR/EBOOT.elf.
    run_elf = os.path.join(disc, "PS3_GAME", "USRDIR", "EBOOT.elf")
    if not fresh([run_elf], [elf]):
        import shutil
        shutil.copyfile(elf, run_elf)
        log("decrypt", f"placed {os.path.relpath(run_elf, ROOT)}")

    # load
    out = os.path.join(GEN, "out")
    fn_json = os.path.join(out, "EBOOT.functions.json")
    imp_json = os.path.join(out, "EBOOT.imports.json")
    if not fresh([fn_json, imp_json], [elf]):
        run("load", [PY, os.path.join(TOOLS, "ppu_loader.py"), elf, "-o", out + "/"])

    # fixfn
    fixed = os.path.join(out, "EBOOT.functions.fixed.json")
    if not fresh([fixed], [fn_json, os.path.join(tools, "fix_functions.py")]):
        run("fixfn", [PY, os.path.join(tools, "fix_functions.py"), elf, fn_json, fixed])

    # lift
    rec = os.path.join(GEN, "recompiled")
    sjlj = os.path.join(ROOT, "config", "sjlj.json")
    patches = os.path.join(ROOT, "config", "insn_patches.json")
    # The lifter leaves unchanged chunks untouched (good for incremental
    # builds), so freshness is tracked with a stamp, not the outputs' mtimes.
    lift_stamp = os.path.join(GEN, ".lift_stamp")
    if not (os.path.exists(os.path.join(rec, "ppu_recomp.h"))
            and fresh([lift_stamp], [fixed, imp_json, sjlj, patches, os.path.join(TOOLS, "ppu_lifter.py")])):
        run("lift", [PY, os.path.join(TOOLS, "ppu_lifter.py"), elf, "--functions", fixed,
                     "--hle-stubs", imp_json, "--sjlj", sjlj, "--insn-patches", patches, "--chunks", PPU_CHUNKS, "-o", rec + "/"])
        open(lift_stamp, "w").close()

    # spu
    spu = os.path.join(GEN, "spu")
    wl = os.path.join(spu, "spu_workloads.c")
    spu_stamp = os.path.join(GEN, ".spu_stamp")
    reloc_cfg = os.path.join(ROOT, "config", "spu_relocatable.json")
    if not (os.path.exists(wl) and fresh([spu_stamp], [elf, reloc_cfg, os.path.join(TOOLS, "spu_lifter.py"), os.path.join(TOOLS, "find_spu_functions.py"),
                                                       os.path.join(TOOLS, "build_spu_workloads.py")])):
        images = os.path.join(spu, "images")
        run("spu", [PY, os.path.join(TOOLS, "extract_spu_images.py"), elf, "--output", images])
        reloc = []
        for img in json.load(open(reloc_cfg))["images"]:
            reloc += ["--relocatable", f"{img}=0x{spu_text_ea(elf, os.path.join(images, img + '.elf')):08X}"]
        run("spu", [PY, os.path.join(TOOLS, "build_spu_workloads.py"), "--images", images,
                    "--lifted", spu, "--out", wl, "--constructor", "--relift", *reloc])
        open(spu_stamp, "w").close()

    log("done", f"generated sources in {os.path.relpath(GEN, ROOT)}/")


if __name__ == "__main__":
    main()
